/** German number format inside a label: 40,000 becomes 40.000, €8,000 becomes 8.000 €, 60% becomes 60 %. */
const numbers = (s: string) =>
  s
    .replace(/€(\d{1,3}(?:,\d{3})*|\d+)/g, (_m, n: string) => `${n.replace(/,/g, ".")} €`)
    .replace(/\d{1,3}(?:,\d{3})+/g, (m) => m.replace(/,/g, "."))
    .replace(/(\d)%/g, "$1 %");

/** The label as it is written in the drawing, in the language of the site. */
export function pixelLabel(s: string): string {
  if (!isDe()) return s;
  const hit = DE[s] ?? DE_MORE[s];
  if (hit !== undefined) return numbers(hit);
  const parts = s.split(/( · |   |  )/);
  if (parts.length > 1) return parts.map((p, i) => (i % 2 ? p : pixelLabel(p))).join("");
  if (/[A-Z]{2}/.test(s) && !/^[\d\s.,%€+\-–·/:()]*$/.test(s)) console.warn("[pixel label without German]", s);
  return numbers(s);
}
